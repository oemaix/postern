#include "nvs_flash.h"
#include "postern.h"

void app_main(void)
{
    esp_err_t err;

    err = postern_init();
    if (err == ESP_ERR_NVS_NO_FREE_PAGES || err == ESP_ERR_NVS_NEW_VERSION_FOUND) {
        ESP_ERROR_CHECK(nvs_flash_erase());
        err = postern_init();
    }
    ESP_ERROR_CHECK(err);
}
